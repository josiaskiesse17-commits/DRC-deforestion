/**
 * Get attribution data for an image by its key.
 */
export function getImageAttribution(key) {
  return IMAGE_ATTRIBUTIONS[key] || null;
}

/**
 * Render an attribution caption for an image.
 */
export function renderImageAttribution(key) {
  const attr = getImageAttribution(key);
  if (!attr) return '';

  return `
    <div class="image-attribution" style="font-size:0.68rem; color:var(--muted); margin-top:6px;">
      <span>Image:</span>
      ${escapeHTML(attr.title)} &middot; ${escapeHTML(attr.date)}<br>
      <span>Source:</span>
      <a href="${escapeHTML(attr.sourceUrl)}" target="_blank" rel="noopener noreferrer">${escapeHTML(attr.source)}</a>
      &middot; ${escapeHTML(attr.license)}
    </div>
  `;
}

/**
 * Escape HTML-sensitive characters.
 */
function escapeHTML(value = '') {
  return String(value).replace(/[&<>"']/g, (character) => {
    const entities = {
      '&': '&amp;',
      '<': '&lt;',
      '>': '&gt;',
      '"': '&quot;',
      "'": '&#39;',
    };
    return entities[character] || character;
  });
}
